--[[
  Nico Comments for OBS
  Niconico Douga-style scrolling comment overlay.

  Install: OBS → Tools → Scripts → "+" → pick this file.
  Keep nico-comments.html in the same folder as this script.

  How it works
  - The comments are drawn on top of the whole OBS output (like the Downstream Keyer plugin),
    so they appear over every scene without being added to any of them.
  - "Hide comments from recordings" (needs the Source Record plugin) keeps a scene called
    "Nico Clean Feed" mirroring whatever scene is live, minus the comments, and records it
    with a Source Record filter. The stream keeps the comments.
]]

obs = obslua

local OVERLAY_NAME  = "Nico Comments Overlay"   -- private browser source owned by this script
local CLEAN_SCENE   = "Nico Clean Feed"
local CLEAN_FILTER  = "Nico Clean Recording"
local SR_FILTER_ID  = "source_record_filter"
local CLEAN_REPLAY_OUTPUT = CLEAN_SCENE .. " - " .. CLEAN_FILTER -- Source Record names its replay output "<scene> - <filter>"
local CHANNEL       = 30                        -- output channel drawn on top of the program scene

-- Source Record "record_mode" values
local MODE_NONE, MODE_STREAMING, MODE_RECORDING, MODE_EITHER = 0, 2, 3, 4

local settings_ref = nil
local overlay = nil
local initialized = false
local hk_show = obs.OBS_INVALID_HOTKEY_ID
local hk_clean = obs.OBS_INVALID_HOTKEY_ID

local function log(msg) obs.script_log(obs.LOG_INFO, msg) end
local function warn(msg) obs.script_log(obs.LOG_WARNING, msg) end

local function dir() return script_path() end
local function html_path() return dir() .. "nico-comments.html" end

-- ------------------------------------------------------------------ config file for the HTML

-- Minimal JSON string escaper for writing nico-config.js
local function js_str(s)
  s = tostring(s or "")
  s = s:gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("\n", "\\n"):gsub("\r", ""):gsub("</", "<\\/")
  return '"' .. s .. '"'
end

local function write_config(s)
  local fields = {
    { "demo",           "bool",   "demo" },
    { "demoRate",       "double", "demo_rate" },
    { "demoBursts",     "bool",   "demo_bursts" },
    { "twitch",         "string", "twitch" },
    { "youtube",        "string", "youtube" },
    { "kick",           "string", "kick" },
    { "ws",             "string", "ws" },
    { "duration",       "double", "duration" },
    { "fixedDuration",  "double", "fixed_duration" },
    { "scale",          "double", "scale" },
    { "bigPct",         "int",    "big_pct" },
    { "smallPct",       "int",    "small_pct" },
    { "jitter",         "int",    "jitter" },
    { "colorPct",       "int",    "color_pct" },
    { "fixedPct",       "int",    "fixed_pct" },
    { "opacity",        "int",    "opacity" },
    { "outline",        "double", "outline" },
    { "font",           "string", "font" },
    { "bold",           "bool",   "bold" },
    { "viewerCommands", "bool",   "viewer_commands" },
    { "ignoreUsers",    "string", "ignore_users" },
    { "maxChars",       "int",    "max_chars" },
  }
  local parts = {}
  for _, f in ipairs(fields) do
    local key, kind, setting = f[1], f[2], f[3]
    local v
    if kind == "bool" then
      v = obs.obs_data_get_bool(s, setting) and "true" or "false"
    elseif kind == "double" then
      v = string.format("%.3f", obs.obs_data_get_double(s, setting))
    elseif kind == "int" then
      v = tostring(obs.obs_data_get_int(s, setting))
    else
      v = js_str(obs.obs_data_get_string(s, setting))
    end
    table.insert(parts, "  " .. key .. ": " .. v)
  end

  local f, err = io.open(dir() .. "nico-config.js", "w")
  if not f then
    warn("Could not write nico-config.js: " .. tostring(err))
    return
  end
  f:write("// Generated by nico-comments.lua. Edit in OBS → Tools → Scripts.\n")
  f:write("window.NICO_CONFIG = {\n" .. table.concat(parts, ",\n") .. "\n};\n")
  f:close()
end

-- ------------------------------------------------------------------ overlay (browser source)

local function browser_settings()
  local ovi = obs.obs_video_info()
  obs.obs_get_video_info(ovi)
  local s = obs.obs_data_create()
  obs.obs_data_set_bool(s, "is_local_file", true)
  obs.obs_data_set_string(s, "local_file", html_path())
  obs.obs_data_set_int(s, "width", ovi.base_width)
  obs.obs_data_set_int(s, "height", ovi.base_height)
  obs.obs_data_set_int(s, "fps", 60)
  obs.obs_data_set_bool(s, "fps_custom", true)
  obs.obs_data_set_bool(s, "shutdown", false)
  obs.obs_data_set_string(s, "css", "body { background-color: rgba(0, 0, 0, 0); margin: 0px auto; overflow: hidden; }")
  return s
end

local function refresh_source(source)
  local props = obs.obs_source_properties(source)
  if props == nil then return end
  local p = obs.obs_properties_get(props, "refreshnocache")
  if p ~= nil then obs.obs_property_button_clicked(p, source) end
  obs.obs_properties_destroy(props)
end

local function ensure_overlay()
  if overlay ~= nil then return end
  local s = browser_settings()
  overlay = obs.obs_source_create_private("browser_source", OVERLAY_NAME, s)
  obs.obs_data_release(s)
end

local function reload_overlay()
  if settings_ref ~= nil then write_config(settings_ref) end
  if overlay == nil then return end
  local s = browser_settings()
  obs.obs_source_update(overlay, s)
  obs.obs_data_release(s)
  refresh_source(overlay)
end

-- ------------------------------------------------------------------ YouTube chat bridge

-- YouTube chat can't be read from inside the overlay page, so youtube-chat.ps1 (plain Windows
-- PowerShell) reads it and serves new messages to the overlay on this local port.
local YT_PORT = 39391

-- LuaJIT FFI lets us launch PowerShell fully hidden (os.execute would flash a console window).
local ffi_ok, ffi = pcall(require, "ffi")
local shell32 = nil
if ffi_ok then
  pcall(ffi.cdef, [[
    int MultiByteToWideChar(unsigned int cp, unsigned long flags, const char *str, int cb, wchar_t *wstr, int cch);
    void *ShellExecuteW(void *hwnd, const wchar_t *op, const wchar_t *file, const wchar_t *params, const wchar_t *dir, int show);
  ]])
  local ok, lib = pcall(ffi.load, "shell32")
  if ok then shell32 = lib end
end

local function wide(s)
  local n = ffi.C.MultiByteToWideChar(65001, 0, s, #s, nil, 0)
  local buf = ffi.new("wchar_t[?]", n + 1) -- zero-filled, so already terminated
  ffi.C.MultiByteToWideChar(65001, 0, s, #s, buf, n)
  return buf
end

-- Start the bridge in the background. A new copy replaces any older one still running.
local function start_youtube_bridge()
  if settings_ref == nil then return end
  local target = obs.obs_data_get_string(settings_ref, "youtube"):gsub('["%c]', ""):match("^%s*(.-)%s*$")
  if target == "" then return end
  local args = string.format('-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "%syoutube-chat.ps1" -Target "%s" -Port %d',
    dir(), target, YT_PORT)
  if shell32 ~= nil then
    shell32.ShellExecuteW(nil, wide("open"), wide("powershell.exe"), wide(args), nil, 0) -- 0 = SW_HIDE
  else
    os.execute('start "" /min powershell.exe ' .. args)
  end
  log("Started YouTube chat reader for " .. target .. " (log: youtube-chat.log)")
end

local function current_scene_name()
  local cur = obs.obs_frontend_get_current_scene()
  if cur == nil then return nil end
  local name = obs.obs_source_get_name(cur)
  obs.obs_source_release(cur)
  return name
end

local function hidden_on(scene_name)
  if scene_name == nil or settings_ref == nil then return false end
  local list = obs.obs_data_get_string(settings_ref, "hide_scenes")
  for name in string.gmatch(list, "[^,]+") do
    if name:match("^%s*(.-)%s*$"):lower() == scene_name:lower() then return true end
  end
  return false
end

-- Put the overlay on (or take it off) the output channel drawn over the program scene.
local function apply_visibility()
  if not initialized or settings_ref == nil then return end
  local show = obs.obs_data_get_bool(settings_ref, "show") and not hidden_on(current_scene_name())
  if show and overlay ~= nil then
    obs.obs_set_output_source(CHANNEL, overlay)
  else
    obs.obs_set_output_source(CHANNEL, nil)
  end
end

-- ------------------------------------------------------------------ clean recording (Source Record)

local function source_record_installed()
  return obs.obs_source_get_display_name(SR_FILTER_ID) ~= nil
end

-- Make sure the "Nico Clean Feed" scene exists and has a Source Record filter on it.
local function ensure_clean_setup()
  if not source_record_installed() then
    warn("Source Record plugin not found, so comments can't be hidden from recordings.")
    return false
  end

  local feed = obs.obs_get_source_by_name(CLEAN_SCENE)
  if feed == nil then
    local scene = obs.obs_scene_create(CLEAN_SCENE)
    feed = obs.obs_scene_get_source(scene)
    obs.obs_source_get_ref(feed)
    obs.obs_scene_release(scene)
    log("Created scene '" .. CLEAN_SCENE .. "' (mirrors your live scene without comments).")
  end

  local filter = obs.obs_source_get_filter_by_name(feed, CLEAN_FILTER)
  if filter == nil then
    local fs = obs.obs_data_create()
    obs.obs_data_set_string(fs, "filename_formatting", "%CCYY-%MM-%DD %hh-%mm-%ss (no comments)")
    filter = obs.obs_source_create(SR_FILTER_ID, CLEAN_FILTER, fs, nil)
    obs.obs_data_release(fs)
    obs.obs_source_filter_add(feed, filter)
    log("Added Source Record filter '" .. CLEAN_FILTER .. "' to '" .. CLEAN_SCENE .. "'.")
  end
  obs.obs_source_release(filter)
  obs.obs_source_release(feed)
  return true
end

-- Point the clean feed at whatever scene is live right now.
local function sync_clean_feed()
  local feed_src = obs.obs_get_source_by_name(CLEAN_SCENE)
  if feed_src == nil then return end
  local cur = obs.obs_frontend_get_current_scene()
  if cur ~= nil then
    local cur_name = obs.obs_source_get_name(cur)
    if cur_name ~= CLEAN_SCENE then
      local feed = obs.obs_scene_from_source(feed_src)
      local items = obs.obs_scene_enum_items(feed) or {}
      local have = false
      for _, it in ipairs(items) do
        if obs.obs_source_get_name(obs.obs_sceneitem_get_source(it)) == cur_name then have = true end
      end
      -- Add the new scene before removing the old one so the recording never sees an empty frame.
      if not have then obs.obs_scene_add(feed, cur) end
      for _, it in ipairs(items) do
        if obs.obs_source_get_name(obs.obs_sceneitem_get_source(it)) ~= cur_name then
          obs.obs_sceneitem_remove(it)
        end
      end
      if #items > 0 then obs.sceneitem_list_release(items) end
    end
    obs.obs_source_release(cur)
  end
  obs.obs_source_release(feed_src)
end

-- Length of OBS's own replay buffer, so the clean replay covers the same stretch of time.
local function main_replay_seconds()
  local cfg = obs.obs_frontend_get_profile_config()
  local sec = 0
  if cfg ~= nil then
    local section = obs.config_get_string(cfg, "Output", "Mode") == "Advanced" and "AdvOut" or "SimpleOutput"
    sec = obs.config_get_int(cfg, section, "RecRBTime")
  end
  if sec == nil or sec <= 0 then sec = 20 end
  return sec
end

-- Folder OBS's own replay buffer saves into.
local function main_replay_dir()
  local out = obs.obs_frontend_get_replay_buffer_output()
  if out == nil then return nil end
  local s = obs.obs_output_get_settings(out)
  local d = obs.obs_data_get_string(s, "directory")
  obs.obs_data_release(s)
  obs.obs_output_release(out)
  if d == nil or d == "" then return nil end
  return d
end

local function profile_dir()
  local ok, p = pcall(obs.obs_frontend_get_current_profile_path)
  if not ok or p == nil or p == "" then
    p = os.getenv("APPDATA") .. "/obs-studio/basic/profiles/" .. obs.obs_frontend_get_current_profile()
  end
  return (p:gsub("\\", "/"):gsub("/+$", "")) .. "/"
end

-- OBS encoder ids → the names Source Record's "encoder" setting expects.
local SR_ENCODER_NAMES = {
  jim_nvenc = "nvenc", obs_nvenc_h264_tex = "nvenc", ffmpeg_nvenc = "nvenc",
  jim_hevc_nvenc = "nvenc_hevc", obs_nvenc_hevc_tex = "nvenc_hevc", ffmpeg_hevc_nvenc = "nvenc_hevc",
  jim_av1_nvenc = "nvenc_av1", obs_nvenc_av1_tex = "nvenc_av1",
  obs_x264 = "x264", obs_qsv11_v2 = "qsv", obs_qsv11_av1 = "qsv_av1",
  h264_texture_amf = "amd", h265_texture_amf = "amd_hevc", av1_texture_amf = "amd_av1",
}

-- The encoder OBS records with: Source Record encoder name, its settings (obs_data or nil), audio bitrate.
local function main_encoder()
  local cfg = obs.obs_frontend_get_profile_config()
  if cfg == nil then return nil end
  local enc, json_file, abr
  if obs.config_get_string(cfg, "Output", "Mode") == "Advanced" then
    enc, json_file = obs.config_get_string(cfg, "AdvOut", "RecEncoder"), "recordEncoder.json"
    if enc == nil or enc == "" or enc:lower() == "none" then -- "Use stream encoder"
      enc, json_file = obs.config_get_string(cfg, "AdvOut", "Encoder"), "streamEncoder.json"
    end
    -- Audio bitrate of the first track the recording uses
    local tracks, idx = obs.config_get_int(cfg, "AdvOut", "RecTracks"), 1
    for i = 1, 6 do
      if math.floor(tracks / 2 ^ (i - 1)) % 2 == 1 then idx = i; break end
    end
    abr = obs.config_get_int(cfg, "AdvOut", "Track" .. idx .. "Bitrate")
  else
    -- Simple mode builds encoder settings from presets, so only the encoder type can be matched.
    local q = (obs.config_get_string(cfg, "SimpleOutput", "RecQuality") or ""):lower()
    if q == "lossless" then return nil end
    enc = obs.config_get_string(cfg, "SimpleOutput", q == "stream" and "StreamEncoder" or "RecEncoder")
  end
  if enc == nil or enc == "" then return nil end
  local data = json_file and obs.obs_data_create_from_json_file(profile_dir() .. json_file) or nil
  return SR_ENCODER_NAMES[enc] or enc, data, abr
end

-- Copy OBS's recording encoder settings into the filter (only when they've changed).
local function match_encoder(s)
  local enc, data, abr = main_encoder()
  if enc == nil then return false end
  local sig = enc .. "|" .. (data and obs.obs_data_get_json(data) or "") .. "|" .. tostring(abr or "")
  local changed = obs.obs_data_get_string(s, "nico_encoder_sig") ~= sig
  if changed then
    obs.obs_data_set_string(s, "encoder", enc)
    if data then obs.obs_data_apply(s, data) end
    if abr and abr > 0 then obs.obs_data_set_int(s, "audio_bitrate", abr) end
    obs.obs_data_set_string(s, "nico_encoder_sig", sig)
    log("Clean recording now matches your recording encoder (" .. enc .. ").")
  end
  if data then obs.obs_data_release(data) end
  return changed
end

-- Apply record mode + replay buffer to the Source Record filter. Only touches the filter when
-- something actually changed, so slider tweaks elsewhere never disturb a running recording.
local function update_filter(filter, mode, replay_on)
  local s = obs.obs_source_get_settings(filter)
  local changed = false
  if obs.obs_data_get_int(s, "record_mode") ~= mode then
    obs.obs_data_set_int(s, "record_mode", mode); changed = true
  end
  if obs.obs_data_get_bool(s, "replay_buffer") ~= replay_on then
    obs.obs_data_set_bool(s, "replay_buffer", replay_on); changed = true
  end
  if mode ~= MODE_NONE or replay_on then
    -- Save clean files next to OBS's own replays (Source Record's default folder can differ).
    local dir_ = main_replay_dir()
    if dir_ ~= nil and obs.obs_data_get_string(s, "path") ~= dir_ then
      obs.obs_data_set_string(s, "path", dir_); changed = true
    end
    if match_encoder(s) then changed = true end
  end
  if replay_on then
    local sec = main_replay_seconds()
    if obs.obs_data_get_int(s, "replay_duration") ~= sec then
      obs.obs_data_set_int(s, "replay_duration", sec); changed = true
    end
  end
  if not obs.obs_data_has_user_value(s, "replay_filename_formatting") then
    obs.obs_data_set_string(s, "replay_filename_formatting", "Replay %CCYY-%MM-%DD %hh-%mm-%ss (no comments)")
    changed = true
  end
  if changed then obs.obs_source_update(filter, s) end
  obs.obs_data_release(s)
  return changed
end

local function apply_clean_mode()
  if not initialized or settings_ref == nil then return end
  local enabled = obs.obs_data_get_bool(settings_ref, "clean_enabled")
  if enabled then
    if not ensure_clean_setup() then return end
    sync_clean_feed()
  end
  local feed = obs.obs_get_source_by_name(CLEAN_SCENE)
  if feed == nil then return end
  local filter = obs.obs_source_get_filter_by_name(feed, CLEAN_FILTER)
  if filter ~= nil then
    local mode = enabled and obs.obs_data_get_int(settings_ref, "clean_when") or MODE_NONE
    -- The clean replay buffer only runs while OBS's own replay buffer does.
    local replay_on = enabled and obs.obs_frontend_replay_buffer_active()
    if update_filter(filter, mode, replay_on) then
      log(enabled and ("Comments hidden from recordings (clean recording on" ..
                       (replay_on and ", clean replay buffer running)." or ")."))
                  or "Comments included in recordings (clean recording off).")
    end
    obs.obs_source_release(filter)
  end
  obs.obs_source_release(feed)
end

-- When OBS saves a replay, save the matching comment-free one too.
local function save_clean_replay()
  local out = obs.obs_get_output_by_name(CLEAN_REPLAY_OUTPUT)
  if out == nil then
    warn("Clean replay buffer isn't running, so no comment-free replay was saved.")
    return
  end
  local cd = obs.calldata_create()
  obs.proc_handler_call(obs.obs_output_get_proc_handler(out), "save", cd)
  obs.calldata_destroy(cd)
  obs.obs_output_release(out)
  log("Saved comment-free replay.")
end

-- ------------------------------------------------------------------ lifecycle

local function init()
  initialized = true
  ensure_overlay()
  start_youtube_bridge()
  apply_visibility()
  apply_clean_mode()
end

local function on_event(event)
  if event == obs.OBS_FRONTEND_EVENT_FINISHED_LOADING
      or event == obs.OBS_FRONTEND_EVENT_SCENE_COLLECTION_CHANGED then
    init()
  elseif event == obs.OBS_FRONTEND_EVENT_SCENE_CHANGED then
    apply_visibility()
    if settings_ref ~= nil and obs.obs_data_get_bool(settings_ref, "clean_enabled") then
      sync_clean_feed()
    end
  elseif event == obs.OBS_FRONTEND_EVENT_REPLAY_BUFFER_STARTED
      or event == obs.OBS_FRONTEND_EVENT_REPLAY_BUFFER_STOPPED then
    apply_clean_mode()
  elseif event == obs.OBS_FRONTEND_EVENT_REPLAY_BUFFER_SAVED then
    if settings_ref ~= nil and obs.obs_data_get_bool(settings_ref, "clean_enabled") then
      save_clean_replay()
    end
  elseif event == obs.OBS_FRONTEND_EVENT_SCENE_COLLECTION_CLEANUP
      or event == obs.OBS_FRONTEND_EVENT_EXIT then
    initialized = false
    obs.obs_set_output_source(CHANNEL, nil)
  end
end

local function toggle(key, on_msg, off_msg)
  if settings_ref == nil then return end
  local v = not obs.obs_data_get_bool(settings_ref, key)
  obs.obs_data_set_bool(settings_ref, key, v)
  if on_msg then log(v and on_msg or off_msg) end
end

