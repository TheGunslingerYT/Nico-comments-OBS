function script_update(s)
  settings_ref = s
  write_config(s)
  -- Visibility and the recording toggle apply instantly; look/chat changes wait for "Apply settings".
  apply_visibility()
  apply_clean_mode()
end

function script_load(s)
  settings_ref = s
  write_config(s)

  hk_show = obs.obs_hotkey_register_frontend("nico_comments_toggle_show",
    "Nico Comments: show / hide comments", function(pressed)
      if not pressed then return end
      toggle("show", "Comments shown.", "Comments hidden.")
      apply_visibility()
    end)
  hk_clean = obs.obs_hotkey_register_frontend("nico_comments_toggle_clean",
    "Nico Comments: toggle hiding comments from recordings", function(pressed)
      if not pressed then return end
      toggle("clean_enabled")
      apply_clean_mode()
    end)
  for key, id in pairs({ nico_hotkey_show = hk_show, nico_hotkey_clean = hk_clean }) do
    local arr = obs.obs_data_get_array(s, key)
    obs.obs_hotkey_load(id, arr)
    obs.obs_data_array_release(arr)
  end

  obs.obs_frontend_add_event_callback(on_event)

  -- Script added while OBS is already running: scenes are loaded, so start now.
  local cur = obs.obs_frontend_get_current_scene()
  if cur ~= nil then
    obs.obs_source_release(cur)
    init()
  end
end

function script_save(s)
  for key, id in pairs({ nico_hotkey_show = hk_show, nico_hotkey_clean = hk_clean }) do
    local arr = obs.obs_hotkey_save(id)
    obs.obs_data_set_array(s, key, arr)
    obs.obs_data_array_release(arr)
  end
end

function script_unload()
  initialized = false
  obs.obs_set_output_source(CHANNEL, nil)
  if overlay ~= nil then
    obs.obs_source_release(overlay)
    overlay = nil
  end
end
